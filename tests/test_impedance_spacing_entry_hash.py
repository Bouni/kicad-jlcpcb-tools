def _entry() -> SpacingReviewEntry:
    """Derive a complete real concern rather than a shortened key fixture."""
    config, snapshot = _config(), _parallel(250_000)
    return spacing_review_entries(config, snapshot, analyze(config, snapshot).sections)[
        0
    ]


def _autogenerated_hash(entry: SpacingReviewEntry) -> int:
    """Apply the exact field selection used by the original generated dataclass hash."""
    return hash(
        tuple(
            getattr(entry, item.name)
            for item in fields(SpacingReviewEntry)
            if (item.compare if item.hash is None else item.hash)
        )
    )


def test_repeated_preview_cache_lookups_do_not_rehash_nested_geometry(
    pane_api: SimpleNamespace,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Real preview history/cache accesses reuse an entry's complete first hash."""
    api = pane_api
    checks = importlib.import_module(api.module.__package__ + ".spacing_checks")
    member = checks.SpacingLocation(
        "source",
        ("mate",),
        (0.0, 1.0),
        ((0, 0), (100, 0)),
        ((0, 250), (100, 250)),
        (0, 0, 100, 250),
    )
    nested_hash = checks.SpacingLocation.__hash__
    calls: list[Any] = []

    def count(location: Any) -> int:
        """Observe real nested dataclass hashing without changing equality or values."""
        calls.append(location)
        return nested_hash(location)

    monkeypatch.setattr(checks.SpacingLocation, "__hash__", count)
    entry = replace(_spacing_entry(api), members=(member,) * 64)
    pane = open_pane(api)
    pane.set_sections((api.section,), "board-a", spacing_entries=(entry,))
    show(api, pane)
    pane.restore_spacing_viewed(
        lambda _entry, _digest: True, {entry: api.capture.sha256}
    )
    assert pane.displayed and calls
    calls.clear()
    for _lookup in range(20):
        pane.refresh_review_labels()
        pane.restore_spacing_viewed(
            lambda _entry, _digest: True, {entry: api.capture.sha256}
        )
        assert pane._viewed[pane._key(pane.entries.index(entry))] == api.capture.sha256
    assert calls == []


@pytest.mark.parametrize("name", [item.name for item in fields(SpacingReviewEntry)])
def test_each_entry_field_retains_its_original_structural_hash_contribution(
    name: str,
) -> None:
    """Matching IDs alone cannot replace exact geometry, presentation, or settings equality."""
    entry = _entry()
    _ = hash(entry)
    original = getattr(entry, name)
    if name == "members":
        value = (replace(original[0], bounds=(1, 2, 3, 4)),) + original[1:]
    elif name in {"source_traces", "mate_traces"}:
        value = (replace(original[0], width_nm=original[0].width_nm + 1),) + original[
            1:
        ]
    elif name == "region_gap_nm":
        value = NmBounds(original.lower_nm + 1, original.upper_nm + 1)
    elif name == "representative":
        value = SpacingCrossSection(
            "other-source", "other-mate", (1, 2), (3, 4), 10, 20
        )
    elif isinstance(original, str):
        value = original + "-changed"
    elif isinstance(original, int):
        value = original + 1
    elif isinstance(original, tuple):
        value = (
            original + (original[-1],)
            if name == "parent_section_ids"
            else tuple(reversed(original))
        )
    else:
        raise AssertionError(f"Add an independent variant for new field {name}")
    changed = replace(entry, **{name: value})
    assert changed != entry
    assert hash(entry) == _autogenerated_hash(entry)
    assert hash(changed) == _autogenerated_hash(changed)
    assert {entry: "original", changed: "changed"} == {
        copy(entry): "original",
        copy(changed): "changed",
    }


def test_hashing_preserves_dataclass_fields_and_cached_composition() -> None:
    """Runtime memo state stays outside canonical fields, IDs, digests, and composition."""
    entry = _entry()
    before = asdict(entry)
    composition = entry.composition
    expected_json = json.dumps(before, sort_keys=True)
    assert hash(entry) == _autogenerated_hash(entry)
    assert asdict(entry) == before
    assert json.dumps(asdict(entry), sort_keys=True) == expected_json
    assert entry.composition is composition
    assert replace(entry) == entry and hash(replace(entry)) == hash(entry)


@dataclass(frozen=True, eq=False)
class _EntryWithIgnoredMetadata(SpacingReviewEntry):
    """An inherited hash must follow inherited base equality for metadata subclasses."""

    metadata: str = ""


def test_inherited_hash_keeps_base_dataclass_equality_contract() -> None:
    """A subclass without generated equality still ignores its extra metadata in hashing."""
    entry = _entry()
    values = {
        item.name: getattr(entry, item.name) for item in fields(SpacingReviewEntry)
    }
    first = _EntryWithIgnoredMetadata(**values, metadata="first")
    second = _EntryWithIgnoredMetadata(**values, metadata="second")
    assert first == second and hash(first) == hash(second) == _autogenerated_hash(entry)
    assert {first: "approved"}[second] == "approved"


@pytest.mark.parametrize(
    "operation", [copy, deepcopy, lambda entry: pickle.loads(pickle.dumps(entry))]
)
def test_copy_and_pickle_round_trips_keep_hash_and_composition(operation: Any) -> None:
    """Copied or restored immutable entries retain full structural lookup compatibility."""
    entry = _entry()
    composition = entry.composition
    expected = hash(entry)
    restored = operation(entry)
    assert restored == entry and hash(restored) == expected == _autogenerated_hash(
        restored
    )
    assert restored.composition == composition
    assert {entry: "reviewed"}[restored] == "reviewed"
    changed = replace(restored, caption=restored.caption + " changed")
    assert changed != entry and hash(changed) == _autogenerated_hash(changed)


class _EntryWithSlots(SpacingReviewEntry):
    """Retain ordinary subclass slot state alongside the base dataclass dictionary."""

    __slots__ = ("metadata",)


class _EntryWithInheritedSlots(_EntryWithSlots):
    """Exercise inherited slots as well as slots on the immediate subclass."""

    __slots__ = ("extra_metadata",)


def _slotted_entry(entry_type: Any) -> Any:
    """Populate real subclass slots without changing the frozen structural fields."""
    entry = _entry()
    values = {
        item.name: getattr(entry, item.name) for item in fields(SpacingReviewEntry)
    }
    result = entry_type(**values)
    object.__setattr__(result, "metadata", ("connector", "J1", {"pad": "D+"}))
    if entry_type is _EntryWithInheritedSlots:
        object.__setattr__(result, "extra_metadata", {"review_note": "retained"})
    return result


@pytest.mark.parametrize("entry_type", [_EntryWithSlots, _EntryWithInheritedSlots])
@pytest.mark.parametrize(
    "operation", [copy, deepcopy, lambda entry: pickle.loads(pickle.dumps(entry))]
)
def test_copy_and_pickle_preserve_all_inherited_subclass_slots(
    entry_type: Any, operation: Any
) -> None:
    """Hash memoization preserves the default dictionary and slot-state round trip."""
    entry = _slotted_entry(entry_type)
    composition = entry.composition
    expected = hash(entry)
    restored = operation(entry)
    assert restored.metadata == entry.metadata
    if entry_type is _EntryWithInheritedSlots:
        assert restored.extra_metadata == entry.extra_metadata
    assert type(restored) is entry_type and restored == entry
    assert restored.composition == composition
    assert hash(restored) == expected == _autogenerated_hash(restored)
    assert {entry: "reviewed"}[restored] == "reviewed"


def test_pickled_entry_recomputes_hash_for_another_process_seed(tmp_path: Path) -> None:
    """An ephemeral hash from one interpreter must never become another process's key."""
    path = tmp_path / "entry.pickle"
    writer = """
from pathlib import Path
import pickle
import sys
from tests.test_impedance_spacing_entry_hash import _slotted_entry, _EntryWithInheritedSlots
entry = _slotted_entry(_EntryWithInheritedSlots)
hash(entry)
entry.composition
Path(sys.argv[1]).write_bytes(pickle.dumps(entry))
"""
    reader = """
from dataclasses import replace
from pathlib import Path
import pickle
import sys
from tests.test_impedance_spacing_entry_hash import _autogenerated_hash
entry = pickle.loads(Path(sys.argv[1]).read_bytes())
assert entry.metadata == ('connector', 'J1', {'pad': 'D+'})
assert entry.extra_metadata == {'review_note': 'retained'}
fresh = replace(entry)
assert hash(entry) == hash(fresh) == _autogenerated_hash(entry)
assert {entry: 'reviewed'}[fresh] == 'reviewed'
"""
    for script, seed in ((writer, "1"), (reader, "2")):
        subprocess.run(
            [sys.executable, "-c", script, str(path)],
            env={**os.environ, "PYTHONHASHSEED": seed},
            check=True,
            capture_output=True,
            text=True,
        )
